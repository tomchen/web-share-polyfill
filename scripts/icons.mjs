// Generates src/icons.ts from Simple Icons (CC0).
// Paths are rescaled from the 24×24 box to integers on a 72×72 box and re-serialized
// as compact relative commands, which roughly halves their size with no visible loss at icon sizes.
//
// Usage: bun scripts/icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import svgpath from 'svgpath'
import * as si from 'simple-icons'

// Icons removed from recent Simple Icons releases, extracted from simple-icons@9 (CC0).
